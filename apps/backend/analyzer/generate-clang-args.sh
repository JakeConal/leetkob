#!/bin/sh
# Generate the compiled-in libclang arguments for the analyzer image.
#
# libclang does not reliably discover a C++ standard library installation
# on its own when parsing a translation unit directly, so the image build
# records the exact include search path that clang itself uses. The paths
# are baked into the binary and never read from the untrusted request.
set -eu

out="${1:-default_clang_args.inc}"
cxx="${CXX:-clang++-19}"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

"$cxx" -E -x c++ -v /dev/null >/dev/null 2>"$tmp" || true
resource_dir="$("$cxx" -print-resource-dir)"

{
    echo '// Generated by generate-clang-args.sh during the image build.'
    echo '// Do not edit by hand.'
    echo 'static const char* const kDefaultClangArgs[] = {'
    printf '  "-resource-dir", "%s",\n' "$resource_dir"
    awk '/#include <...> search starts here:/{flag=1;next} /End of search list./{flag=0} flag' "$tmp" \
        | sed 's/^[[:space:]]*//; s/[[:space:]]*$//' \
        | while IFS= read -r path; do
            if [ -n "$path" ]; then
                printf '  "-I%s",\n' "$path"
            fi
        done
    echo '};'
} >"$out"
